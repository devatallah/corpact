<?php

namespace App\Services\Reporting\Export;

/**
 * A13 — تصنيف حساسية عمود التصدير (H §15، G/الشركة §5، G/قائد المجتمع).
 *
 * قيدان نصّيان في المواصفة يُطبَّقان **على العمود لا على الصفحة**:
 * 1. «أرقام جوال الموظفين لا تظهر في أي تصدير **إلا لمسؤول الحساب**».
 * 2. «القائد يصدّر بيانات مجتمعه **بلا أي بيانات مالية**».
 *
 * وضعهما على العمود يعني أن تصديراً جديداً يرث القيد تلقائياً: من يضيف عموداً
 * جوالاً أو مبلغاً يصنّفه هنا، ولا يحتاج أن يتذكر شرطاً في كل صفحة.
 */
enum ExportSensitivity: string
{
    case Plain = 'plain';

    /** رقم جوال — لمسؤول الحساب وحده. */
    case Phone = 'phone';

    /** بيانات مالية — يُحجب عن قائد المجتمع. */
    case Financial = 'financial';
}
